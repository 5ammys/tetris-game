Piece Piece_create(PieceType type){
    Piece p;
    p.type      = type;
    p.rotation  = 0;
    p.col       = 3;
    p.row       = 0;

    return p;
}

Piece Piece_createRandom(){
    return  Piece_create((PieceType)(rand() % PIECE_COUNT));
}
