Piece Piece_create(PieceType type)
{
    Piece p;
    p.type=type;
    p.rotation=0;
    p.col=3;
    p.row=0;

    return p;
}

Piece Piece_createRandom()
{
    return  Piece_create((PieceType)(rand() % PIECE_COUNT));
}

SDL_Color Piece_getColor(PieceType type)
{
    if (type<0 || type> PIECE_COUNT)
    {
        SDL_Color defaultColor = {200, 200, 200, 255}; //gris por defecto
        return defaultColor;
    }
    return PIECE_COLORS[type];
}

int Piece_getBlock(PieceType type, int rotation, int r, int c)
{
    if (type<0 || type>=PIECE_COUNT) return 0;
    if (rotation<0 || rotation>=4) return 0;
    if (r<0 || r>=PIECE_GRID_SIZE) return 0;
    if (c<0 || c>=PIECE_GRID_SIZE) return 0;

    return SHAPE[type][rotation][r][c];
}
